# -*- coding: utf-8 -*-
"""做一杯奶茶：同一个目标，两种做法。

顾客要求：少糖。合格范围是甜度 3 到 5。

跑法：python3 examples/00_奶茶.py
"""


# ============ 三个动作，两边共用 ============

def 加糖(甜度):
    """加三勺糖。"""
    return 甜度 + 6


def 加奶(甜度):
    """加奶会把甜味压下去一点。"""
    return 甜度 - 2


def 合格(甜度):
    """甜度在 3 到 5 之间，算合格。"""
    return 3 <= 甜度 <= 5


# ============ 做法一：店长写死的流程 ============
# 走哪几步，代码里写得清清楚楚。

print("=== 做法一：店长写好的流程（workflow）===")

甜度 = 0
print("第 1 步 倒茶，甜度 =", 甜度)

甜度 = 加糖(甜度)
print("第 2 步 加 3 勺糖，甜度 =", 甜度)

print("第 3 步 尝一口，甜度 =", 甜度)

if 甜度 > 5:                      # 这个 if 是"店长"写的
    甜度 = 加奶(甜度)
    print("第 4 步 太甜了，加奶，甜度 =", 甜度)
else:
    print("第 4 步 不用加奶")

print("第 5 步 出杯，甜度 =", 甜度)


# ============ 做法二：店长只说"做好喝点" ============
# 没有写死的步骤。每做一步，先问一次"店员的脑子"。

def 店员的脑子(甜度, 尝过):
    """这里是大模型站的位置。它看当前情况，决定下一步做什么。"""
    if 甜度 == 0:
        return "加糖"        # 一点甜味都没有，先加糖
    if not 尝过:
        return "尝一口"      # 还没尝过，先尝
    if 甜度 > 5:
        return "加奶"        # 太甜，加奶压一压
    return "出杯"            # 合格了，出杯


print()
print("=== 做法二：店长只说「做好喝点」（agent）===")

甜度 = 0
尝过 = False

for 第几步 in range(1, 9):
    动作 = 店员的脑子(甜度, 尝过)
    print("第 %d 步 店员决定：%s" % (第几步, 动作))

    if 动作 == "出杯":
        break
    if 动作 == "加糖":
        甜度 = 加糖(甜度)
    elif 动作 == "尝一口":
        尝过 = True
    elif 动作 == "加奶":
        甜度 = 加奶(甜度)

print("出杯，甜度 =", 甜度)

print()
print("两杯奶茶一模一样。")
print("差别只有一处：第一种里「太甜就加奶」是第 4 步那个 if（店长写的），")
print("            第二种里没人写这个 if —— 它在店员的脑子里。")
